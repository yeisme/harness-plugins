function pseudoLongValue(value: string): string {
  return `［ ${value.replace(/([aeiou])/giu, '$1$1')} ··· ］`
}

function pseudoRtlValue(value: string): string {
  return `⟦RTL ${[...value].reverse().join('')}⟧`
}

export const pseudoLong = Object.fromEntries(Object.entries(en).map(([key, value]) => [key, pseudoLongValue(value)])) as Readonly<Record<CreatorStudioKey, string>>
export const pseudoRtl = Object.fromEntries(Object.entries(en).map(([key, value]) => [key, pseudoRtlValue(value)])) as Readonly<Record<CreatorStudioKey, string>>

const TABLES: Record<CreatorStudioLocale, Readonly<Record<CreatorStudioKey, string>>> = {
  zh,
  en,
  'pseudo-long': pseudoLong,
  'pseudo-rtl': pseudoRtl,
}

function format(value: string, params?: Readonly<Record<string, string | number>>): string {
  if (params === undefined) return value
  return value.replace(/\{([a-zA-Z0-9_]+)\}/gu, (_match, key: string) => String(params[key] ?? `{${key}}`))
}

export function createCreatorStudioTranslator(locale: CreatorStudioLocale = 'zh'): CreatorStudioTranslator {
  const table = TABLES[locale]
  return (key, params) => format(table[key] ?? en[key], params)
}

export const defaultCreatorStudioTranslator = createCreatorStudioTranslator('zh')

