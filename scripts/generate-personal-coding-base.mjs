#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageDir = resolve(root, 'packages/bundle/dsh-personal-coding-base')
const check = process.argv.slice(2).includes('--check')

const rows = [
  ['dsh-command-experience', '@yeisme/dsh-command-experience'],
  ['dsh-workbench-core', '@yeisme/dsh-workbench-core'],
  ['dsh-desktop-workbench', '@yeisme/dsh-desktop-workbench'],
  ['dsh-semantic-file-editor', '@yeisme/dsh-semantic-file-editor'],
  ['dsh-terminal', '@yeisme/dsh-terminal/host'],
  ['dsh-devtools', '@yeisme/dsh-devtools'],
  ['ordo-agent-ops', '@yeisme/dsh-ordo-agent-ops'],
]

const dependencies = {
  '@yeisme/dsh-command-experience': 'workspace:*',
  '@yeisme/dsh-desktop-workbench': 'workspace:*',
  '@yeisme/dsh-devtools': 'workspace:*',
  '@yeisme/dsh-ordo-agent-ops': 'workspace:*',
  '@yeisme/dsh-plugin-contracts': 'workspace:*',
  '@yeisme/dsh-semantic-file-editor': 'workspace:*',
  '@yeisme/dsh-terminal': 'workspace:*',
  '@yeisme/dsh-workbench-core': 'workspace:*',
}

const plugin = [
  '/** Composition marker plugin. Member plugins are sibling DSH profile layers. */',
  "export const name = 'dsh-personal-coding-base'",
  'export const inject = []',
  'export function apply() {}',
  '',
].join('\n')

const manifest = {
  name: '@yeisme/dsh-personal-coding-base',
  version: '0.1.0-rc.1',
  description: 'Minimal DSH personal coding profile bundle: commands, workbench files/Git, semantic editor, terminal, diagnostics, structured plugin contracts, and optional Ordo projection',
  license: 'MIT',
  type: 'module',
  private: true,
  main: 'lib/index.js',
  exports: {
    '.': './lib/index.js',
    './cordis.patch.yml': './cordis.patch.yml',
    './package.json': './package.json',
  },
  files: ['lib/index.js', 'cordis.patch.yml', 'README.md'],
  scripts: {
    'generate:assets': 'node ../../../scripts/generate-personal-coding-base.mjs',
    test: 'node ../../../scripts/generate-personal-coding-base.mjs --check && node --test tests/base-contract.test.mjs',
  },
  dsh: {
    bundle: { patch: './cordis.patch.yml', composition: true },
    personalCoding: {
      packId: 'base',
      tier: 'base',
      critical: true,
      dependencies: [],
      criticalContributions: ['dsh-command-experience', 'dsh-workbench-core', 'dsh-desktop-workbench', 'dsh-semantic-file-editor', 'dsh-terminal', 'dsh-devtools'],
      optionalContributions: ['ordo-agent-ops'],
    },
  },
  dependencies,
}

const patch = [
  '# Generated by scripts/generate-personal-coding-base.mjs. Do not edit by hand.',
  '# Composition marker only. Member plugins are sibling DSH profile layers',
  '# installed by `dsh-tui setup`; this patch MUST NOT re-insert their ids',
  '# because DSH treats duplicate loader ids as a fatal plugin-tree failure.',
  '# Members:',
  ...rows.map(([id, name]) => `#   ${id} ${name}`),
  '# Install:',
  '#   dsh-tui setup --source <yeisme-agent-root> --yes',
  '- insert:',
  "    - id: dsh-personal-coding-base",
  "      name: '@yeisme/dsh-personal-coding-base'",
  '',
].join('\n')

const outputs = new Map([
  [resolve(packageDir, 'package.json'), `${JSON.stringify(manifest, null, 2)}\n`],
  [resolve(packageDir, 'cordis.patch.yml'), patch],
  [resolve(packageDir, 'lib/index.js'), plugin],
])

let drift = false
for (const [path, expected] of outputs) {
  if (check) {
    let actual = ''
    try {
      actual = await readFile(path, 'utf8')
    } catch {
      drift = true
      process.stderr.write(`missing generated asset: ${path.slice(root.length + 1)}\n`)
      continue
    }
    if (actual !== expected) {
      drift = true
      process.stderr.write(`generated asset drift: ${path.slice(root.length + 1)}\n`)
    }
    continue
  }
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, expected, 'utf8')
  process.stdout.write(`generated ${path.slice(root.length + 1)}\n`)
}

if (drift) process.exitCode = 1
