import assert from 'node:assert/strict'
import {writeFile} from 'node:fs/promises'

/** Extends the existing browser runner; no business calls or user file mutations. */
export async function verifySessionTools(page, directory, sessionA, step = () => {}) {
  const quote = value => JSON.stringify(value)
  const conversation = id => page.locator(`[data-workspace-pane=${quote(`conversation:${id}`)}]`)
  const tab = id => page.locator(`[data-workspace-tab=${quote(`conversation:${id}`)}]`)
  const companion = id => page.locator(`[data-workspace-pane*="mcp-inspector"][data-session-ref=${quote(id)}]`)
  const inspector = root => root.locator('[data-mcp-inspector]')
  const openTools = async id => { step(`${id===sessionA?'A':'B'}-select-conversation`); await tab(id).click(); step(`${id===sessionA?'A':'B'}-select-tools-tab`); await conversation(id).getByRole('tab', {name:/^(Tools|工具)$/}).click(); await inspector(conversation(id)).waitFor() }
  const pin = async id => { step(`${id===sessionA?'A':'B'}-pin-button`); await inspector(conversation(id)).getByRole('button', {name:/^(Pin to side pane|固定到旁栏)$/}).click(); step(`${id===sessionA?'A':'B'}-pin-visible`); await companion(id).waitFor() }
  const checks = []
  step('catalog')
  await inspector(conversation(sessionA)).waitFor()
  await page.waitForFunction(id => document.querySelector(`[data-workspace-pane="conversation:${id}"] [data-mcp-inspector]`)?.getAttribute('data-catalog-state') === 'ready', sessionA)
  step('pin-A')
  await pin(sessionA)
  assert.equal(await companion(sessionA).count(), 1)
  assert.equal(await companion(sessionA).locator('.tools-toggle').count(), 0)
  await tab(sessionA).click()
  const candidates = page.locator('[data-workspace-session-id]')
  let sessionB
  for (let i=0;i<await candidates.count();i++) { const id=await candidates.nth(i).getAttribute('data-workspace-session-id');if(id && id!==sessionA){sessionB=id;await candidates.nth(i).click();break} }
  assert(sessionB, 'A second Session is required for affinity acceptance')
  step('pin-B')
  await tab(sessionB).dblclick(); step('B-tools-tab'); await openTools(sessionB); step('B-companion'); await pin(sessionB)
  assert.equal(await companion(sessionA).count(),1)
  assert.equal(await companion(sessionB).count(),1)
  step('B-repeat-pin'); await openTools(sessionB); await pin(sessionB)
  assert.equal(await companion(sessionB).count(),1)
  checks.push('A/B tools tabs and pinned panes have distinct identities; repeated pin reuses the existing pane')
  await tab(sessionA).click()
  step('close-source')
  const closeA=tab(sessionA).locator('..').getByRole('button',{name:/^(Close|关闭) / })
  await closeA.click(); await tab(sessionA).waitFor({state:'detached'})
  assert.equal(await companion(sessionA).count(),1)
  const paneAId=await companion(sessionA).getAttribute('data-workspace-pane')
  await page.locator(`[data-workspace-tab=${quote(paneAId)}]`).click()
  await companion(sessionA).getByRole('button',{name:/^(Open conversation|打开会话)$/}).click()
  await tab(sessionA).waitFor()
  checks.push('Closing A conversation leaves its companion alive and its title action reopens A')
  step('reload')
  await page.reload(); await companion(sessionA).waitFor({state:'attached'}); await companion(sessionB).waitFor({state:'attached'})
  assert.equal(await companion(sessionA).count(),1);assert.equal(await companion(sessionB).count(),1)
  checks.push('Reload restores both fixed Session bindings')
  step('title-session-management')
  const aPaneId = await companion(sessionA).getAttribute('data-workspace-pane')
  await page.locator(`[data-workspace-tab=${quote(aPaneId)}]`).click()
  const group = page.locator(`[data-workspace-tab=${quote(aPaneId)}]`).locator('xpath=ancestor::*[@data-workspace-group][1]')
  step('title-open-menu'); await group.locator('[data-workspace-session-menu]').click()
  const picker = page.getByRole('dialog', {name:/^(Add pane|添加面板)$/})
  step('title-search'); await picker.getByRole('textbox').fill(sessionB)
  step('title-choose'); await picker.locator(`[data-workspace-catalog-session=${quote(sessionB)}]`).click()
  step('title-rebound'); await companion(sessionA).waitFor({state:'detached'})
  assert.equal(await companion(sessionB).count(),1)
  await openTools(sessionA); await pin(sessionA)
  checks.push('Pane title search explicitly rebinds A to B and deduplicates the existing B companion')
  await openTools(sessionB)
  const bTools=inspector(conversation(sessionB))
  step('call-details')
  await bTools.waitFor()
  const rows=bTools.locator('.tools-activity-row:not([data-running=true]) .tools-record-name')
  if(await rows.count()) {
    step('call-select'); await rows.first().click(); step('call-reveal'); await bTools.locator('.tools-call-details').waitFor()
    await bTools.getByRole('button',{name:/^(Reveal original message|定位原消息)$/}).click()
    step('call-land'); await conversation(sessionB).locator('[data-chat-anchor-key]:focus').waitFor()
    checks.push('Call details navigate to the original message in B, not the global current Session')
  } else checks.push('No historical calls in selected B; original-message navigation covered by fixture tests')
  await openTools(sessionA)
  const aTools=inspector(conversation(sessionA))
  await aTools.screenshot({path:new URL('artifacts/session-tools-redacted.png',directory).pathname,mask:[aTools.locator('.tools-record-name'),aTools.locator('.tools-call-details'),aTools.locator('.tools-row-title'),aTools.locator('.tools-row-description')],maskColor:'#333333'})
  step('global-settings')
  await aTools.getByRole('button',{name:/^(Manage global tools|管理全局工具)$/}).click()
  const global=page.locator('[data-workspace-pane*="tools-manager"]')
  await global.waitFor()
  await global.getByRole('button',{name:/^(Installation and connection settings|安装与连接设置)$/}).click()
  await page.getByRole('button',{name:/^(Plugins|插件)$/}).waitFor()
  await page.keyboard.press('Escape')
  checks.push('Global management opens the existing settings owner without executing a configuration mutation')
  await writeFile(new URL('artifacts/session-tools-checks.json',directory),JSON.stringify({checks,redacted:true,sessionCount:2}))
  // Restore the original conversation for the existing general Pane checks.
  await tab(sessionA).click()
  const chat=conversation(sessionA).getByRole('tab',{name:/^(Chat|对话|聊天)$/})
  if(await chat.count())await chat.click()
  return checks
}
