for (const theme of ['light', 'dark']) test(`search text and keyboard focus contrast in ${theme}`, async ({ page }) => {
  await page.goto(`/search-center?width=960&lang=en&theme=${theme}`)
  const input = page.getByRole('combobox', { name: /Search sessions/ })
  await input.focus()
  const contrast = await input.evaluate(element => {
    const field = element.closest('.pwr-search-input')!
    const background = getComputedStyle(field).backgroundColor
    const style = getComputedStyle(element)
    const canvas = document.createElement('canvas'); canvas.width = 1; canvas.height = 1
    const ctx = canvas.getContext('2d')!
    const luminance = (color: string) => {
      ctx.clearRect(0, 0, 1, 1); ctx.fillStyle = background; ctx.fillRect(0, 0, 1, 1)
      ctx.fillStyle = color; ctx.fillRect(0, 0, 1, 1)
      const values = [...ctx.getImageData(0, 0, 1, 1).data].slice(0, 3).map(value => {
        const channel = value / 255; return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4
      })
      return values[0]! * 0.2126 + values[1]! * 0.7152 + values[2]! * 0.0722
    }
    const base = luminance(background)
    const ratio = (color: string) => { const foreground = luminance(color); return (Math.max(base, foreground) + 0.05) / (Math.min(base, foreground) + 0.05) }
    return { text: ratio(style.color), focus: ratio(style.outlineColor), outline: style.outlineStyle }
  })
  expect(contrast.text).toBeGreaterThanOrEqual(4.5)
  expect(contrast.outline).not.toBe('none')
  expect(contrast.focus).toBeGreaterThanOrEqual(3)
})

