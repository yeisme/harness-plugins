test('coarse pointer controls and official menu items meet 44px touch targets', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 360, height: 850 }, hasTouch: true, reducedMotion: 'reduce' })
  try {
    const page = await context.newPage()
    await page.goto('http://127.0.0.1:4178/search-center?width=360&lang=en&mode=pane')
    expect(await page.evaluate(() => matchMedia('(pointer:coarse)').matches)).toBe(true)
    const input = page.getByRole('combobox', { name: /Search sessions/ })
    await input.fill('Document 0')
    await expect(page.getByRole('option', { name: 'Document 0' })).toBeVisible()
    const undersized = await page.locator('[data-workspace-search="pane"]').evaluate(root =>
      [...root.querySelectorAll<HTMLElement>('button,input,select')].filter(element => element.getClientRects().length > 0)
        .filter(element => { const rect = element.getBoundingClientRect(); return rect.width < 44 || rect.height < 44 })
        .map(element => element.getAttribute('aria-label') ?? element.textContent))
    expect(undersized).toEqual([])
    await page.getByRole('button', { name: 'Actions for selected result' }).tap()
    const first = page.getByRole('menuitem', { name: 'Open to the right' })
    await expect(first).toBeVisible()
    for (const item of await page.getByRole('menuitem').all()) {
      const rect = await item.boundingBox()
      expect(rect!.height).toBeGreaterThanOrEqual(44)
      expect(rect!.width).toBeGreaterThanOrEqual(44)
    }
    expect(await page.locator('[data-workspace-search="pane"]').evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0s')
    expect(await page.evaluate(() => (window as any).fixtureExecutions)).toBe(0)
  } finally { await context.close() }
})

